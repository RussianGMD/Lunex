def merge_theme(base: dict, override: dict) -> dict:
    result = copy.deepcopy(base)
    if not isinstance(override, dict):
        return result
    for k, v in override.items():
        if isinstance(v, dict) and isinstance(result.get(k), dict):
            result[k] = merge_theme(result[k], v)
        else:
            result[k] = v
    return result


def ensure_example_theme(themes_dir: str, example_file: str):
    try:
        os.makedirs(themes_dir, exist_ok=True)
        if not os.path.isfile(example_file):
            with open(example_file, "wb") as f:
                f.write(orjson.dumps(BLACK_THEME, option=orjson.OPT_INDENT_2))
        else:
            with open(example_file, "rb") as f:
                existing = orjson.loads(f.read())
            if isinstance(existing, dict):
                merged = merge_theme(BLACK_THEME, existing)
                if merged != existing:
                    with open(example_file, "wb") as f:
                        f.write(orjson.dumps(merged, option=orjson.OPT_INDENT_2))
    except Exception:
        pass


def get_available_themes(themes_dir: str) -> list[str]:
    themes = ["Black (Standart)", "White"]
    try:
        if os.path.isdir(themes_dir):
            json_files = sorted(
                f for f in os.listdir(themes_dir)
                if f.lower().endswith(".json") and os.path.isfile(os.path.join(themes_dir, f))
            )
            for jf in json_files:
                if jf not in themes:
                    themes.append(jf)
    except Exception:
        pass
    return themes


def resolve_theme_data(themes_dir: str, theme_name: str) -> dict:
    if theme_name == "Black (Standart)" or not theme_name:
        return copy.deepcopy(BLACK_THEME)
    if theme_name == "White":
        return copy.deepcopy(WHITE_THEME)

    candidates = [os.path.join(themes_dir, theme_name)]
    if not theme_name.lower().endswith(".json"):
        candidates.append(os.path.join(themes_dir, f"{theme_name}.json"))

    for path in candidates:
        if os.path.isfile(path):
            try:
                with open(path, "rb") as f:
                    loaded = orjson.loads(f.read())
                if isinstance(loaded, dict):
                    return merge_theme(BLACK_THEME, loaded)
            except Exception:
                break

    return copy.deepcopy(BLACK_THEME)